// Builds assets/js/emoji-data.js for the live demo from the same data the app ships.
// Run: node website/tools/build-emoji-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../../src/EmojiAnywhere/Data/", import.meta.url);
const read = (f) => JSON.parse(readFileSync(new URL(f, dir), "utf8"));
const data = read("compact.json");
const codes = {};
for (const f of ["iamcal.json", "github.json"]) {
  for (const [hex, v] of Object.entries(read(f))) {
    const list = (codes[hex] ??= []);
    for (const c of [].concat(v)) if (!list.includes(c.toLowerCase())) list.push(c.toLowerCase());
  }
}
const out = [];
for (const e of data) {
  if (e.order === undefined || !codes[e.hexcode]) continue; // base emojis that have a shortcode
  out.push([e.unicode, codes[e.hexcode], (e.tags ?? []).map((t) => t.toLowerCase())]);
}
writeFileSync(new URL("../assets/js/emoji-data.js", import.meta.url),
  "// Generated by tools/build-emoji-data.mjs from emojibase-data (MIT). Do not edit.\nwindow.EMOJI_DATA=" + JSON.stringify(out) + ";\n");
console.log(`wrote ${out.length} emojis`);
